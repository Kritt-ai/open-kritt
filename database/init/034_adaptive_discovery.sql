-- An opt-in exploration frontier is distinct from findings and post-processing.
CREATE TABLE IF NOT EXISTS workflows.discovery_frontiers (
    scan_id bigint PRIMARY KEY,
    workflow_id bigint NOT NULL,
    step_id bigint NOT NULL,
    max_paths integer NOT NULL CHECK (max_paths BETWEEN 1 AND 1000),
    wall_time_seconds integer NOT NULL CHECK (wall_time_seconds BETWEEN 1 AND 86400),
    status text DEFAULT 'running' NOT NULL
        CHECK (status IN ('running', 'exhausted', 'blocked', 'budget_stopped')),
    reason text,
    budget_reason text,
    started_at timestamptz DEFAULT clock_timestamp() NOT NULL,
    deadline_at timestamptz NOT NULL,
    updated_at timestamptz DEFAULT clock_timestamp() NOT NULL
);

CREATE TABLE IF NOT EXISTS workflows.discovery_paths (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id bigint NOT NULL,
    step_id bigint NOT NULL,
    parent_path_id bigint,
    path_key text NOT NULL,
    scope text NOT NULL,
    question text NOT NULL,
    rationale text NOT NULL,
    status text DEFAULT 'pending' NOT NULL
        CHECK (status IN ('pending', 'running', 'completed', 'blocked', 'budget_stopped')),
    reason text,
    metadata_id bigint,
    proposals jsonb DEFAULT '[]'::jsonb NOT NULL,
    completion jsonb,
    inserted_at timestamptz DEFAULT clock_timestamp() NOT NULL,
    updated_at timestamptz DEFAULT clock_timestamp() NOT NULL,
    CONSTRAINT discovery_paths_scan_path_key UNIQUE (scan_id, path_key)
);

CREATE INDEX IF NOT EXISTS discovery_paths_scan_status_idx
    ON workflows.discovery_paths (scan_id, status, id);
